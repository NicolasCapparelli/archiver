import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const require = createRequire(path.join(process.env.CODEX_NODE_MODULES, 'package.json'));
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.join(root,'index.html')).href);
await page.evaluate(()=>document.fonts.ready);
await page.locator('#cover').screenshot({path:path.join(root,'qa','cover.png')});
await page.locator('#quick-light').screenshot({path:path.join(root,'qa','librarian-light.png')});
await page.locator('#archive-light').screenshot({path:path.join(root,'qa','archivist-light.png')});
await page.locator('#quick-dark').screenshot({path:path.join(root,'qa','librarian-dark.png')});
await page.locator('#archive-dark').screenshot({path:path.join(root,'qa','archivist-dark.png')});
await page.locator('#theme-toggle').click();
if(await page.locator('#quick-light').getAttribute('data-theme')!=='dark')throw new Error('Theme toggle failed');
await page.locator('#scope-toggle').click();
if(!await page.locator('#quick-light .q-search').innerText().then(t=>t.includes('Archive')))throw new Error('Archive scope failed');
await page.locator('#quick-state').selectOption('empty');
if(!await page.locator('#quick-light .q-empty').innerText().then(t=>t.includes('Your library is clear')))throw new Error('Empty state failed');
await page.locator('[data-demo-scope]').click();
if(await page.locator('#quick-state').inputValue()!=='results')throw new Error('Empty state archive transition failed');
await page.locator('#quick-state').selectOption('error');
await page.locator('[data-demo-retry]').click();
if(await page.locator('#quick-state').inputValue()!=='results')throw new Error('Retry state failed');
await page.locator('#archive-light [data-record="5"]').click();
if(!await page.locator('#archive-light .a-detail').innerText().then(t=>t.includes('Failed · Exit 1')))throw new Error('Record detail selection failed');
await page.locator('#quick-light [data-preview-tab="Commands"]').click();
if(await page.locator('#quick-light [data-record]').count()!==3)throw new Error('Command sample filtering failed');
await page.locator('#theme-toggle').click();
await page.reload();await page.evaluate(()=>document.fonts.ready);
await page.emulateMedia({media:'print'});
const overflow=await page.evaluate(()=>[...document.querySelectorAll('.sheet')].map(el=>{
 const s=el.getBoundingClientRect();const footer=el.querySelector('.page-footer').getBoundingClientRect();
 const kids=[...el.children].filter(k=>!k.matches('.page-footer')).map(k=>({tag:k.tagName,bottom:k.getBoundingClientRect().bottom-s.top}));
 return {id:el.id,width:s.width,height:s.height,footerTop:footer.top-s.top,contentBottom:Math.max(...kids.map(k=>k.bottom)),scrollHeight:el.scrollHeight};
}));
fs.writeFileSync(path.join(root,'qa','layout-report.json'),JSON.stringify({errors,overflow},null,2));
if(errors.length||overflow.some(o=>o.contentBottom>o.footerTop-12||o.scrollHeight>850))throw new Error('Print layout overflow; see layout-report.json');
await page.pdf({path:path.join(root,'Archiver-design-study.pdf'),printBackground:true,preferCSSPageSize:true});
await page.emulateMedia({media:'screen'});
await page.setViewportSize({width:390,height:844});
const mobile=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
fs.writeFileSync(path.join(root,'qa','interaction-report.json'),JSON.stringify({errors,mobile,checks:['theme toggle','archive scope','empty library','include archive','search retry','detail selection','command filtering']},null,2));
if(mobile.scrollWidth>mobile.width)throw new Error('Page overflows mobile viewport');
await page.locator('#librarian').screenshot({path:path.join(root,'qa','mobile-librarian.png')});
await browser.close();console.log('Study rendered; interactions and page bounds verified.');

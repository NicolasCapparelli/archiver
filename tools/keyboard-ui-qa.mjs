// Built-frontend browser checks with isolated sample data; no native archive writes.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(path.join(process.env.CODEX_NODE_MODULES, 'package.json'));
const { chromium } = require('playwright');
const out = path.resolve('continuity/design/reading-room/qa/keyboard-ui');
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
try {
  for (const theme of ['light', 'dark']) {
    const context = await browser.newContext({ viewport: { width: 1280, height: 850 } });
    await context.addInitScript(theme => localStorage.setItem('archiver-theme', theme), theme);
    await context.route('http://127.0.0.1:1439/**', route => {
      const url = new URL(route.request().url());
      const file = path.resolve('dist', '.' + (url.pathname === '/' ? '/index.html' : url.pathname));
      assert.ok(file.startsWith(path.resolve('dist') + path.sep));
      const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.woff2': 'font/woff2', '.woff': 'font/woff', '.svg': 'image/svg+xml' };
      return route.fulfill({ body: fs.readFileSync(file), contentType: types[path.extname(file)] || 'application/octet-stream' });
    });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:1439/');
    await page.locator('.entry').first().waitFor();
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.locator('.clip-groups input, .clip-groups select').count(), 0);
    await page.screenshot({ animations: 'disabled', path: path.join(out, `archivist-${theme}.png`) });
    await page.keyboard.press('Control+Alt+g');
    await page.getByRole('dialog', { name: 'New group', exact: true }).waitFor();
    await page.locator('#new-group').fill('Writing');
    await page.screenshot({ animations: 'disabled', path: path.join(out, `new-group-${theme}.png`) });
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Writing', exact: true }).waitFor();
    assert.equal(await page.locator('dialog[open]').count(), 0);
    await page.getByRole('button', { name: 'All groups', exact: true }).click();
    await page.setViewportSize({ width: 650, height: 700 });
    await page.screenshot({ animations: 'disabled', path: path.join(out, `archivist-narrow-${theme}.png`) });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 480, height: 720 });
    await page.goto('http://127.0.0.1:1439/?quick=1');
    await page.locator('.entry').first().waitFor();
    await page.waitForFunction(() => document.activeElement?.matches('.entry,.item-list'));
    await page.keyboard.press('s');
    assert.ok(await page.locator('.entry.selected').evaluate(node => node === document.activeElement));
    assert.equal(await page.locator('.entry.selected').evaluate(node => getComputedStyle(node).outlineStyle), 'none');
    await page.screenshot({ animations: 'disabled', path: path.join(out, `librarian-${theme}.png`) });
    await page.keyboard.press('Control+o');
    await page.getByRole('dialog', { name: 'Full clip', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Save as snippet', exact: true }).count(), 0);
    await page.screenshot({ animations: 'disabled', path: path.join(out, `full-clip-${theme}.png`) });
    await page.keyboard.press('Control+Alt+s');
    await page.getByRole('heading', { name: 'New snippet', exact: true }).waitFor();
    const editor = page.locator('dialog[open]').last();
    await editor.getByLabel('Name', { exact: true }).fill('QA snippet');
    await editor.getByLabel('Note (kept separate from pasted text)', { exact: true }).fill('Private note');
    await page.keyboard.press('Control+t');
    await page.getByRole('dialog', { name: 'Transform snippet', exact: true }).waitFor();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await page.getByRole('dialog', { name: 'Transform snippet', exact: true }).waitFor({ state: 'detached' });
    assert.equal(await page.locator('dialog[open]').count(), 1);
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === null && document.activeElement?.tagName === 'TEXTAREA');
    await page.keyboard.press('Control+s');
    await page.getByRole('heading', { name: 'New snippet', exact: true }).waitFor({ state: 'detached' });
    await page.locator('.entry.selected').filter({ hasText: 'QA snippet' }).waitFor();
    await page.waitForFunction(() => document.activeElement?.matches('.entry,.item-list'));
    await page.keyboard.press('Control+t');
    await page.getByRole('heading', { name: 'Edit snippet', exact: true }).waitFor();
    assert.equal(await page.locator('dialog[open]').getByLabel(/^Note \(kept separate/).inputValue(), 'Private note');
    await page.screenshot({ animations: 'disabled', path: path.join(out, `snippet-editor-${theme}.png`) });
    await page.keyboard.press('Escape');
    await page.keyboard.press('Control+Shift+n');
    await page.getByRole('textbox', { name: 'Paste Playground', exact: true }).fill('Playground text');
    await page.keyboard.press('Control+Alt+s');
    await page.getByRole('heading', { name: 'New snippet', exact: true }).waitFor();
    assert.equal(await page.locator('dialog[open]').getByLabel(/^Content/).inputValue(), 'Playground text');
    await context.close();
  }
  assert.deepEqual(errors, []);
  console.log('Both themes: group creation, narrow layout, WASD/single border, Full clip/Playground snippet shortcut, snippet transform/save/note/focus checks passed. Native move/drop remains pending.');
} finally { await browser.close(); }

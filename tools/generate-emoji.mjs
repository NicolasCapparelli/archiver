// Unicode 16.0 source and license are retained in src/data; no network at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
let group = '', subgroup = '';
const entries = [];
for (const line of readFileSync('src/data/emoji-test.txt', 'utf8').split('\n')) {
  if (line.startsWith('# group: ')) group = line.slice(9).trim();
  if (line.startsWith('# subgroup: ')) subgroup = line.slice(12).trim();
  const match = line.match(/^([A-F0-9 ]+)\s*; fully-qualified\s*# \S+ E[\d.]+ (.+)$/);
  if (match) entries.push([String.fromCodePoint(...match[1].trim().split(/\s+/).map(hex => parseInt(hex, 16))), match[2].trim(), group, subgroup]);
}
writeFileSync('src/data/emoji.ts', '// Generated by tools/generate-emoji.mjs from Unicode 16.0. See UNICODE-LICENSE.txt.\nexport const emojiData: readonly (readonly string[])[] = ' + JSON.stringify(entries) + ';\n');
console.log(`Generated ${entries.length} emoji sequences`);
